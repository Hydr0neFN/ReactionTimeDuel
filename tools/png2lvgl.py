#!/usr/bin/env python3
"""Convert a PNG to an LVGL 8 C image (LV_IMG_CF_TRUE_COLOR_ALPHA, RGB565 little endian + alpha byte).

Usage: python tools/png2lvgl.py <in.png> <out.c> [--name ui_img_xxx]

The output has the layout of the SquareLine Studio files in firmware/display/lib/ui/images
(3 bytes per pixel: RGB565 low byte, RGB565 high byte, alpha). Needs Pillow.
"""

import argparse
import os
import re
import sys

from PIL import Image

PER_LINE = 32


def default_name(png_path):
    base = os.path.splitext(os.path.basename(png_path))[0]
    base = re.sub(r"[^0-9A-Za-z_]", "_", base)
    return base if base.startswith("ui_img_") else "ui_img_" + base


def rgba_to_bytes(img):
    out = bytearray()
    raw = img.tobytes()  # RGBA, 4 bytes per pixel
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i:i + 4]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((v & 0xFF, v >> 8, a))
    return out


def write_c(path, name, width, height, data, src_name):
    lines = []
    for i in range(0, len(data), PER_LINE):
        lines.append(",".join("0x%02X" % b for b in data[i:i + PER_LINE]) + ",")
    text = (
        '// Generated by tools/png2lvgl.py from %s\n'
        '// LVGL version: 8.3.11, format LV_IMG_CF_TRUE_COLOR_ALPHA (RGB565 little endian + alpha)\n'
        '\n'
        '#include "../ui.h"\n'
        '\n'
        '#ifndef LV_ATTRIBUTE_MEM_ALIGN\n'
        '#define LV_ATTRIBUTE_MEM_ALIGN\n'
        '#endif\n'
        '\n'
        'const LV_ATTRIBUTE_MEM_ALIGN uint8_t %s_data[] = {\n'
        '%s\n'
        '    };\n'
        'const lv_img_dsc_t %s = {\n'
        '   .header.always_zero = 0,\n'
        '   .header.w = %d,\n'
        '   .header.h = %d,\n'
        '   .data_size = sizeof(%s_data),\n'
        '   .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,\n'
        '   .data = %s_data};\n'
    ) % (src_name, name, "\n".join(lines), name, width, height, name, name)
    with open(path, "w", newline="\n") as f:
        f.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("input", help="input PNG")
    ap.add_argument("output", help="output C file")
    ap.add_argument("--name", help="C symbol of the lv_img_dsc_t (default ui_img_<file name>)")
    args = ap.parse_args(argv)

    name = args.name or default_name(args.input)
    img = Image.open(args.input).convert("RGBA")
    write_c(args.output, name, img.width, img.height, rgba_to_bytes(img), os.path.basename(args.input))
    print("%s: %dx%d -> %s (%s)" % (args.input, img.width, img.height, args.output, name))
    return 0


if __name__ == "__main__":
    sys.exit(main())
